class MarineKnowledgeService:
    """
    Central service for the Shared Marine Knowledge Layer:
    - Structured numeric queries over ingested timeseries (wave, wind, SST, pressure).
    - Source-aware document retrieval over verified marine science, regulations, and safety facts.
    - Preserves provenance, unit normalization, and freshness timestamps.
    """
    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(MarineKnowledgeService, cls).__new__(cls)
            cls._instance.db = DatabaseManager()
            cls._instance._seed_verified_knowledge()
        return cls._instance

    def _seed_verified_knowledge(self) -> None:
        """Seeds canonical marine documents on startup if none exist."""
        try:
            for doc in INITIAL_VERIFIED_MARINE_KNOWLEDGE:
                self.db.upsert_knowledge_document(doc)
            logger.info("Shared marine knowledge layer initialized with canonical reference documents.")
        except Exception as e:
            logger.warning(f"Could not seed marine knowledge documents: {e}")

    def search_unstructured_knowledge(
        self,
        query: str,
        category: Optional[str] = None,
        coastal_region: Optional[str] = None,
        limit: int = 3
    ) -> List[Dict[str, Any]]:
        """
        Retrieves verified marine knowledge documents with source attribution and citations.
        Never substitutes for numeric sensor timeseries queries.
        """
        return self.db.search_knowledge_documents(
            query=query,
            category=category,
            coastal_region=coastal_region,
            limit=limit
        )

    def query_numeric_timeseries(
        self,
        parameter: Optional[str] = None,
        lat: Optional[float] = None,
        lon: Optional[float] = None,
        radius_km: float = 75.0,
        start_time: Optional[str] = None,
        end_time: Optional[str] = None,
        limit: int = 25
    ) -> List[Dict[str, Any]]:
        """
        Executes strict structured SQL query for physical oceanographic numbers.
        """
        return self.db.query_timeseries_records(
            parameter=parameter,
            lat=lat,
            lon=lon,
            radius_km=radius_km,
            start_time=start_time,
            end_time=end_time,
            limit=limit
        )

    def get_knowledge_summary(self) -> Dict[str, Any]:
        """Provides an inventory of available knowledge documents and records."""
        with self.db.get_connection() as conn:
            doc_count = conn.execute("SELECT COUNT(*) as count FROM marine_knowledge_documents WHERE is_verified = 1;").fetchone()["count"]
            ts_count = conn.execute("SELECT COUNT(*) as count FROM marine_timeseries_records;").fetchone()["count"]
            cats = [r["category"] for r in conn.execute("SELECT DISTINCT category FROM marine_knowledge_documents;").fetchall()]
            params = [r["parameter"] for r in conn.execute("SELECT DISTINCT parameter FROM marine_timeseries_records;").fetchall()]

            return {
                "verified_documents_count": doc_count,
                "timeseries_records_count": ts_count,
                "document_categories": cats,
                "tracked_numeric_parameters": params,
                "status": "OPERATIONAL"
            }
